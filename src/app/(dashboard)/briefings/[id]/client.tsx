"use client";

import Link from "next/link";
import { ArrowLeft, FileText, Calendar, ExternalLink } from "lucide-react";
import type { Briefing, NewsArticle } from "@/lib/supabase/queries";
import { formatDate } from "@/lib/utils";
import { RelevanceBadge } from "@/components/shared/relevance-badge";
import { cn } from "@/lib/utils";

interface Props {
  briefing: Briefing | undefined;
  articles: NewsArticle[];
}

export function BriefingDetailClient({ briefing, articles }: Props) {
  if (!briefing) {
    return (
      <div className="max-w-[1280px] mx-auto py-12 text-center">
        <FileText className="h-12 w-12 mx-auto text-foreground-muted/50" />
        <h2 className="mt-4 text-lg font-semibold">Briefing not found</h2>
        <Link href="/briefings" className="mt-2 text-sm text-primary hover:underline">
          Back to Briefings
        </Link>
      </div>
    );
  }

  return (
    <div className="max-w-[1280px] mx-auto space-y-6">
      <Link href="/briefings" className="inline-flex items-center gap-1 text-sm text-foreground-muted hover:text-primary">
        <ArrowLeft className="h-3.5 w-3.5" /> Briefings
      </Link>

      <div>
        <div className="flex items-center gap-2 mb-2">
          <span className={cn(
            "rounded px-2 py-0.5 text-[10px] font-semibold uppercase",
            briefing.type === "daily"
              ? "bg-info/10 text-info"
              : "bg-accent/10 text-accent"
          )}>
            {briefing.type}
          </span>
          <span className="flex items-center gap-1 text-xs text-foreground-muted">
            <Calendar className="h-3 w-3" />
            {formatDate(briefing.generatedAt)}
          </span>
        </div>
        <h1 className="text-2xl font-bold text-foreground">{briefing.title}</h1>
      </div>

      <div className="grid gap-6 lg:grid-cols-3">
        <div className="lg:col-span-2 space-y-6">
          <div className="rounded-lg border border-border p-5">
            <h3 className="text-sm font-semibold uppercase tracking-wider text-foreground-muted mb-3">Executive Summary</h3>
            <p className="text-sm leading-relaxed">{briefing.summary}</p>
          </div>

          <div className="rounded-lg border border-border p-5">
            <h3 className="text-sm font-semibold uppercase tracking-wider text-foreground-muted mb-3">Key Highlights</h3>
            <ul className="space-y-3">
              {briefing.highlights.map((highlight, i) => (
                <li key={i} className="flex gap-3 text-sm">
                  <span className="flex h-5 w-5 items-center justify-center rounded-full bg-primary text-[10px] font-bold text-white shrink-0 mt-0.5">
                    {i + 1}
                  </span>
                  <span>{highlight}</span>
                </li>
              ))}
            </ul>
          </div>

          <p className="text-xs text-foreground-muted italic">
            This briefing was generated by AI analysis of {briefing.articleCount} public news articles. All information is sourced from public materials. No confidential or privileged information has been used.
          </p>
        </div>

        <div>
          <h3 className="text-sm font-semibold uppercase tracking-wider text-foreground-muted mb-3">Source Articles</h3>
          <div className="space-y-3">
            {articles.map((article) => (
              <div key={article.id} className="rounded-lg border border-border p-3">
                <span className="text-xs text-foreground-muted">
                  {article.source} · {formatDate(article.publishedAt)}
                </span>
                <p className="text-sm font-medium mt-1 line-clamp-2">{article.headline}</p>
                <div className="flex items-center gap-2 mt-2">
                  <RelevanceBadge score={article.relevanceScore} label="REL" />
                  <a href={article.sourceUrl} target="_blank" rel="noopener noreferrer"
                    className="inline-flex items-center gap-1 text-[10px] text-primary hover:underline ml-auto">
                    Source <ExternalLink className="h-3 w-3" />
                  </a>
                </div>
              </div>
            ))}
          </div>
        </div>
      </div>
    </div>
  );
}
